create table public.facilities (
  id smallint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 2 and 80)
);

create unique index facilities_name_lower_idx on public.facilities (lower(name));

create table public.utilities (
  id smallint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 2 and 80)
);

create unique index utilities_name_lower_idx on public.utilities (lower(name));

create table public.boarding_house_facilities (
  boarding_house_id uuid not null references public.boarding_houses (id) on delete cascade,
  facility_id smallint not null references public.facilities (id) on delete restrict,
  primary key (boarding_house_id, facility_id)
);

create table public.boarding_house_utilities (
  boarding_house_id uuid not null references public.boarding_houses (id) on delete cascade,
  utility_id smallint not null references public.utilities (id) on delete restrict,
  is_included boolean not null,
  details text check (details is null or char_length(trim(details)) between 1 and 240),
  primary key (boarding_house_id, utility_id)
);

create table public.house_rules (
  id uuid primary key default gen_random_uuid(),
  boarding_house_id uuid not null references public.boarding_houses (id) on delete cascade,
  rule_text text not null check (char_length(trim(rule_text)) between 3 and 500),
  position integer not null check (position between 1 and 100),
  unique (boarding_house_id, position)
);

