create policy "boarding_house_facilities_select_visible_listing"
on public.boarding_house_facilities
for select
to anon, authenticated
using (
  exists (
    select 1 from public.boarding_houses
    where boarding_houses.id = boarding_house_facilities.boarding_house_id
  )
);

create policy "boarding_house_facilities_manage_owner_or_admin"
on public.boarding_house_facilities
for all
to authenticated
using (
  public.current_user_is_admin()
  or exists (
    select 1 from public.boarding_houses
    where boarding_houses.id = boarding_house_facilities.boarding_house_id
      and boarding_houses.owner_id = (select auth.uid())
      and public.current_user_is_owner()
  )
)
with check (
  public.current_user_is_admin()
  or exists (
    select 1 from public.boarding_houses
    where boarding_houses.id = boarding_house_facilities.boarding_house_id
      and boarding_houses.owner_id = (select auth.uid())
      and public.current_user_is_owner()
  )
);

