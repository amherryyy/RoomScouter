create function public.queue_listing_attribute_review()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_listing_id uuid;
begin
  if tg_op = 'DELETE' then
    target_listing_id := old.boarding_house_id;
  else
    target_listing_id := new.boarding_house_id;
  end if;

  if (select auth.uid()) is not null and not public.current_user_is_admin() then
    update public.boarding_houses
    set status = 'pending',
        submitted_at = now(),
        moderated_at = null,
        moderated_by = null,
        moderation_note = null
    where id = target_listing_id
      and owner_id = (select auth.uid())
      and status = 'approved';
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

revoke all on function public.queue_listing_attribute_review() from public;

create trigger boarding_house_facilities_queue_review
after insert or update or delete on public.boarding_house_facilities
for each row execute function public.queue_listing_attribute_review();

create trigger boarding_house_utilities_queue_review
after insert or update or delete on public.boarding_house_utilities
for each row execute function public.queue_listing_attribute_review();

create trigger house_rules_queue_review
after insert or update or delete on public.house_rules
for each row execute function public.queue_listing_attribute_review();

